import { spawn } from "node:child_process";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve, join } from "node:path";
import { fileURLToPath } from "node:url";
const desktop = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const root = resolve(desktop, "../..");
const artifacts = join(root, "output/playwright", `interview-overlay-${Date.now()}`);
await mkdir(artifacts, { recursive: true });
let output = "";
const env = {...process.env,INTERVIEW_COPILOT_DISABLE_GPU:"1",INTERVIEW_COPILOT_TEST_DATA_PATH:join(artifacts,"data"),INTERVIEW_OVERLAY_ARTIFACT_DIR:artifacts};
delete env.ELECTRON_RUN_AS_NODE;
const child = spawn(process.env.ELECTRON_EXECUTABLE ?? join(root, "node_modules/electron/dist/electron.exe"), ["--disable-gpu", "--in-process-gpu", `--user-data-dir=${join(artifacts,"browser")}`, ...(process.env.ELECTRON_PACKAGED === "true" ? [] : [desktop]), "--interview-overlay-smoke"], {cwd:desktop, windowsHide:true, env,stdio:["ignore","pipe","pipe"]});
for (const stream of [child.stdout, child.stderr]) stream.on("data", chunk => {output += String(chunk);process.stdout.write(chunk);});
const timer = setTimeout(() => child.kill(), 60000);
const code = await new Promise((resolve, reject) => {child.once("close", resolve);child.once("error", reject);});
clearTimeout(timer);
await writeFile(join(artifacts,"run.log"),output);
process.stdout.write(`ARTIFACTS ${artifacts}\n`);
process.exitCode = code === 0 && output.includes('INTERVIEW_OVERLAY_SMOKE_RESULT {"ok":true') ? 0 : 1;
